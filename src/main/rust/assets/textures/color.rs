const MIN_BITS: u32 = 0x3900_0000;
const MAX_BITS: u32 = 0x3f7f_ffff;

/// `ColorSRGB.srgbToLinear`.
#[inline]
pub(crate) fn srgb_to_linear(component: u8) -> f32 {
    FROM_SRGB8_TABLE[component as usize]
}

/// `ColorSRGB.linearToSrgb(float)`.
#[inline]
pub(crate) fn linear_to_srgb(component: f32) -> u8 {
    let min = f32::from_bits(MIN_BITS);
    let max = f32::from_bits(MAX_BITS);
    // `!(c > min)` also catches NaN.
    let mut clamped = component;
    if !(clamped > min) {
        clamped = min;
    }
    if clamped > max {
        clamped = max;
    }
    let bits = clamped.to_bits();
    let entry = TO_SRGB8_TABLE[((bits - MIN_BITS) >> 20) as usize];
    let bias = (entry >> 16) << 9;
    let scale = entry & 0xffff;
    let t = (bits >> 12) & 0xff;
    ((bias + scale * t) >> 16) as u8
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn conversions_round_trip_bytes() {
        for value in 0..=255u8 {
            assert_eq!(value, linear_to_srgb(srgb_to_linear(value)), "byte {value}");
        }
        assert_eq!(0, linear_to_srgb(f32::NAN));
        assert_eq!(255, linear_to_srgb(2.0));
    }
}
